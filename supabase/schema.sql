-- Receipts are private to the authenticated user who created them.
create table if not exists public.receipts (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  customer_name text not null check (char_length(customer_name) between 1 and 120),
  phone text null check (phone is null or char_length(phone) <= 30),
  service text not null check (char_length(service) between 1 and 250),
  amount numeric(12,2) null check (amount is null or amount >= 0),
  status text not null default 'قيد المتابعة' check (status in ('قيد المتابعة', 'مكتملة', 'تحتاج مستندات', 'ملغاة')),
  created_at timestamptz not null default now()
);

create index if not exists receipts_user_created_idx on public.receipts (user_id, created_at desc);
alter table public.receipts enable row level security;
revoke all on table public.receipts from anon;
grant select, insert, delete on table public.receipts to authenticated;
grant usage, select on sequence public.receipts_id_seq to authenticated;

drop policy if exists "Users can read their own receipts" on public.receipts;
create policy "Users can read their own receipts" on public.receipts for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users can insert their own receipts" on public.receipts;
create policy "Users can insert their own receipts" on public.receipts for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can delete their own receipts" on public.receipts;
create policy "Users can delete their own receipts" on public.receipts for delete to authenticated using ((select auth.uid()) = user_id);
